import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { ExpertEncoding } from "./pdfjs-encodings.js";

const root = dirname(fileURLToPath(import.meta.url));
const pdfjsWorker = process.argv[2];
if (pdfjsWorker === undefined) {
  throw new Error("usage: bun generate-cff-tables.ts <pdfjs-dist/build/pdf.worker.mjs>");
}
const source = readFileSync(pdfjsWorker, "utf8");

const extractArray = (name: string): ReadonlyArray<string> => {
  const match = new RegExp(`const ${name} = (\\[[^\\]]*\\]);`).exec(source);
  if (match === null || match[1] === undefined) {
    throw new Error(`missing ${name}`);
  }
  return JSON.parse(match[1]);
};

const standardStrings = extractArray("CFFStandardStrings");
const expertCharset = extractArray("ExpertCharset");
const expertSubsetCharset = extractArray("ExpertSubsetCharset");
if (standardStrings.length !== 391) {
  throw new Error(`unexpected standard string count ${standardStrings.length}`);
}

const sid = (name: string): number => {
  const index = standardStrings.indexOf(name);
  if (index < 0) {
    throw new Error(`unknown CFF standard string ${name}`);
  }
  return index;
};

const expertEncoding = Array.from({ length: 256 }, (_, code) => {
  const name = ExpertEncoding[code];
  return name === undefined || name === "" ? 0 : sid(name);
});

const numbers = (values: ReadonlyArray<number>) => {
  const lines: Array<string> = [];
  for (let index = 0; index < values.length; index += 16) {
    lines.push(`    ${values.slice(index, index + 16).join(", ")},`);
  }
  return lines.join("\n");
};

const output = `// @generated by shared/pdf-core/scripts/generate-cff-tables.ts

pub const CFF_STANDARD_STRINGS: [&str; 391] = [
${standardStrings.map((value) => `    ${JSON.stringify(value)},`).join("\n")}
];

pub const CFF_EXPERT_CHARSET: &[u16] = &[
${numbers(expertCharset.map(sid))}
];

pub const CFF_EXPERT_SUBSET_CHARSET: &[u16] = &[
${numbers(expertSubsetCharset.map(sid))}
];

pub const CFF_EXPERT_ENCODING: [u16; 256] = [
${numbers(expertEncoding)}
];
`;

writeFileSync(join(root, "../rust/src/cff_tables.rs"), output);
